/**
 * State Transition Map
 * Defines valid transition paths and transition interpolation duration in ms
 */
const ULTRON_TRANSITIONS = {
  defaultDuration: 350,
  durations: {
    'idle->listening': 280,
    'listening->thinking': 320,
    'thinking->processing': 300,
    'processing->working': 300,
    'working->speaking': 350,
    'speaking->idle': 400,
    'idle->boot': 600,
    'boot->idle': 700,
    'idle->sleep': 800,
    'sleep->idle': 500,
    'idle->shutdown': 900,
    'shutdown->offline': 400,
    'offline->reconnecting': 500,
    'reconnecting->idle': 450,
  },
  getDuration(from, to) {
    const key = `${from}->${to}`;
    return this.durations[key] || this.defaultDuration;
  },
};

